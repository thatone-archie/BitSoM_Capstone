## chargeback_ratio (per-merchant) = (count of that merchant's transactions with status == "chargeback") / (count of all of that merchant's transactions).




## From df_ledger, group by merchant_id, get sum of transaction counts; order by sum of amount_inr desc
df_merchant_amount = df_ledger.groupby('merchant_id')['transaction_id'].count().reset_index()
df_merchant_amount = df_merchant_amount.sort_values(by='transaction_id', ascending=False)


#Limit top 10 records from merchant_summary
