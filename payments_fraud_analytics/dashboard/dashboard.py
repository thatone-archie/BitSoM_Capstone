# Calculate total transactions for each merchant
df_total_txns_per_merchant = df_ledger.groupby('merchant_id')['transaction_id'].count().reset_index()
df_total_txns_per_merchant.columns = ['merchant_id', 'merchant_total_txn_cnt']

# Merge this new DataFrame with df_merchant_chargeback
df_merchant_chargeback = pd.merge(df_merchant_chargeback, df_total_txns_per_merchant, on='merchant_id', how='right')



###%%%%%

#Add another column to df_merchant_chargeback called 'merchant_chargeback_ratio' = (count of transactions with lower(status) == "chargeback" for that merchant) / (count of all of that merchant's transactions)) * 100
df_merchant_chargeback['merchant_chargeback_ratio'] = (df_merchant_chargeback['cnt_of_chargebacks'] / df_merchant_chargeback["merchant_total_txn_cnt"] ) * 100

#For merchant_id = 19, print df_merchant_amount, print df_merchant_chargeback








# If merchant does not have any chargebacks in df_merchant_chargeback, then the columns: cnt_of_chargebacks, merchant_chargeback_ratio value will be 0
