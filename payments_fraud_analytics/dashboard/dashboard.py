df_merchant_amount.columns = ['merchant_id','merchant_txn_counts']


#From df_ledger, create a new df called df_merchant_chargeback, group by merchant_id, sum of count of txns i.e. where lower(status) = chargeback
df_merchant_chargeback = df_ledger[df_ledger['status'].str.lower() == 'chargeback'].groupby('merchant_id')['transaction_id'].count().reset_index()

df_merchant_chargeback.columns = ['merchant_id','cnt_of_chargebacks']


## Add  another column to df_merchant_chargeback called merchant_total_txn_cnt, which is group by merchant_id, sum of count of total txns
