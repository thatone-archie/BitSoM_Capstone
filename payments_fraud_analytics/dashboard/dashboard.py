df_merchant_summary['cnt_of_chargebacks'] = df_merchant_summary['cnt_of_chargebacks'].apply(lambda x: '{:.0f}'.format(x))
df_merchant_summary['merchant_chargeback_ratio'] = df_merchant_summary['merchant_chargeback_ratio'].apply(lambda x: '{:.2f}%'.format(x))







